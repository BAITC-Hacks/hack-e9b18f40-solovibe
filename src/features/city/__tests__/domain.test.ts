test('V2 exhaustive certificates and V4 proven conflicts', async () => {
    const memory = process.memoryUsage().rss;
    let r = await searchPlans({ datasetVersion: ds.version, constraints: DEFAULT_CONSTRAINTS, deadlineMs: 60000 });
    assert.equal(r.status, 'complete');
    assert.equal(r.validCount, 694395);
    near(r.candidates[0].evaluation.score, 57.236735);
    assert.equal(r.certificate?.inputHash, r.inputHash);
    console.log(`full search ${Math.round(r.elapsedMs)}ms; RSS delta ${Math.round((process.memoryUsage().rss - memory) / 1048576)} MiB`);
    r = await searchPlans({ datasetVersion: ds.version, constraints: { ...DEFAULT_CONSTRAINTS, requiredDirections: [...DIRECTIONS] }, deadlineMs: 60000 });
    assert.equal(r.validCount, 68200);
    near(r.candidates[0].evaluation.score, 56.344510);
    assert.equal(r.candidates[0].evaluation.criticalPairs.length, 1);
    r = await searchPlans({ datasetVersion: ds.version, constraints: { ...DEFAULT_CONSTRAINTS, minDirectDistricts: 2 }, deadlineMs: 60000 });
    near(r.candidates[0].evaluation.score, 56.9977);
    r = await searchPlans({ datasetVersion: ds.version, constraints: { ...DEFAULT_CONSTRAINTS, requiredDirections: [...DIRECTIONS], maxCriticalPairs: 0 }, deadlineMs: 60000 });
    assert.equal(r.status, 'complete');
    assert.equal(r.feasibleCount, 0);
    assert.ok(r.issues.some(i => i.code === 'NURA_REQUIRES_TWO_SOCIAL'));
    r = await searchPlans({ datasetVersion: ds.version, constraints: { ...DEFAULT_CONSTRAINTS, locked: [{ measureId: 'M7', districtId: 'nura' }], excludedMeasureIds: ['M7'] } });
    assert.equal(r.feasibleCount, 0);
    assert.ok(r.issues.some(i => i.code === 'LOCK_EXCLUDED'));
    const controller = new AbortController();
    controller.abort();
    r = await searchPlans({ datasetVersion: ds.version, constraints: DEFAULT_CONSTRAINTS, signal: controller.signal });
    assert.equal(r.termination, 'cancelled');
    assert.equal(r.certificate, null);
    r = await searchPlans({ datasetVersion: ds.version, constraints: DEFAULT_CONSTRAINTS, deadlineMs: 0 });
    assert.equal(r.termination, 'deadline');
});
test('C2 locks, floors, objective, bounded cancellation and cache isolation', async () => {
    const locked = [{ measureId: 'M7' as const, districtId: 'nura' as const }];
    const constraints = { ...DEFAULT_CONSTRAINTS, locked, objective: 'minCost' as const, districtFloors: [{ districtId: 'nura' as const, minScore: 50 }], indicatorFloors: [{ districtId: 'nura' as const, indicatorId: 'S1' as const, minValue: 48 }] };
    const r = await searchPlans({ datasetVersion: ds.version, constraints, deadlineMs: 60000 });
    assert.equal(r.status, 'complete');
    assert.ok(r.candidates.length);
    for (const c of r.candidates) {
        assert.ok(c.decisions.some(d => d.measureId === 'M7' && d.districtId === 'nura'));
        assert.ok(c.evaluation.districts[4].score >= 50);
        assert.ok(c.evaluation.districts[4].indicators[4].after >= 48);
    }
    assert.equal(r.certificate?.bestValue, r.candidates[0].evaluation.cost);
    r.candidates[0].decisions.length = 0;
    const cached = await searchPlans({ datasetVersion: ds.version, constraints });
    assert.equal(cached.candidates[0].decisions.length, 5);
    const controller = new AbortController();
    setTimeout(() => controller.abort(), 5);
    const stopped = await searchPlans({ datasetVersion: ds.version, constraints: { ...DEFAULT_CONSTRAINTS, maxSpend: 99 }, signal: controller.signal });
    assert.equal(stopped.termination, 'cancelled');
    assert.equal(stopped.certificate, null);
    assert.ok(stopped.evaluatedCount > 0);
    assert.ok(stopped.elapsedMs < 1000);
});
