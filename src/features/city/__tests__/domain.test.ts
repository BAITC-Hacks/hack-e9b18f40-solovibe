const near = (actual: number | null, expected: number) => assert.ok(actual !== null && Math.abs(actual - expected) < 1e-9, `${actual} != ${expected}`);
test('V1 source arithmetic, exact immutable source and evidence', () => {
    near(evaluateBaseline(ds).score, 52.55768);
    const r = evaluate(ds, EXAMPLE_DECISIONS);
    near(r.score, 56.54307);
    assert.equal(r.cost, 95);
    assert.equal(r.criticalPairs.length, 0);
    assert.equal(r.districts.flatMap(d => d.indicators).length, 50);
    assert.deepEqual(r, evaluate(ds, [...EXAMPLE_DECISIONS].reverse()));
    assert.equal(evaluate(ds, []).score, null);
    assert.equal(evaluate(ds, EXAMPLE_DECISIONS.slice(0, 4)).score, null);
    assert.equal(evaluate(ds, OPTIMUM).score, 57.236735);
    near(evaluate(ds, TWO_DISTRICTS).score, 56.9977);
    assert.equal(createHash('sha256').update(readFileSync('data/akim-dataset.md')).digest('hex'), ds.sourceHash);
    const { canonicalHash, ...payload } = ds;
    assert.equal(createHash('sha256').update(stableJson(payload)).digest('hex'), canonicalHash);
    assert.ok(Object.isFrozen(ds.measures[0].effects));
    near(Object.values(ds.weights).reduce((a, b) => a + b), 1);
    near(ds.districts.reduce((a, b) => a + b.populationShare, 0), 1);
    assert.deepEqual(evaluateBaseline(ds).districts.map(d => d.score), [62.99, 57.06, 54.65, 56.63, 49.18]);
    assert.ok(evidenceGraph(r, r.evidence.at(-1)!.id).length > 100);
    assert.throws(() => readEvidence(r, ['unknown']));
    assert.ok(r.evidence.some(e => e.kind === 'synergy' && e.value === 2));
});
